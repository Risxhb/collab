# Rebuilds models/arcanist.glb (WebP, browser) and the Unity copy (JPEG) from the Meshy sources with Blender, then
# wraps the browser GLB in arcanist-glb.js so pages opened from disk (file://) can load it.
#   powershell -File build-arcanist.ps1 -RunRef <Soldier.glb> [-Source <meshy body .glb>] [-Astrolabe <meshy astrolabe .glb>] [-Unity <out .glb>]
param(
  [string]$Source = (Get-ChildItem (Join-Path $PSScriptRoot 'upload\Meshy') -Filter '*Arcanist_Body*texture.glb' | Select-Object -First 1).FullName,
  [string]$Astrolabe = (Get-ChildItem (Join-Path $PSScriptRoot 'upload\Meshy') -Filter '*Arcanist_Astrolabe*texture.glb' | Select-Object -First 1).FullName,
  [string]$Blender = 'C:\Program Files\Blender Foundation\Blender 5.2\blender.exe',
  # Mixamo-skeleton GLB whose 'Run' clip drives Run/Sprint (three.js examples/models/gltf/Soldier.glb). Not committed.
  [Parameter(Mandatory = $true)][string]$RunRef,
  [string]$Unity = (Join-Path $PSScriptRoot '..\..\..\unity\Assets\LastBell\Characters\Arcanist\Resources\Characters\Arcanist.glb')
)
$ErrorActionPreference = 'Stop'
$work = Join-Path $env:TEMP 'lastbell-arcanist-build'; New-Item -ItemType Directory -Force $work | Out-Null
$glb = Join-Path $PSScriptRoot 'arcanist.glb'
New-Item -ItemType Directory -Force (Split-Path $Unity) | Out-Null
& $Blender -b -P (Join-Path $PSScriptRoot 'blender\arcanist_prep.py') -- $Source $work 50000 $Astrolabe | Select-String '^(TRIS|ASTRO_TRIS|GLOW)|Error|Traceback'
& $Blender -b (Join-Path $work 'arcanist_prep.blend') -P (Join-Path $PSScriptRoot 'blender\arcanist_rig.py') -- $work $glb $RunRef $Unity | Select-String '^(WEIGHTS|SEAMS|SLIVERS|STANCE|MOCAP|EXPORTED)|Error|Traceback'
$b64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($glb))
Set-Content (Join-Path $PSScriptRoot 'arcanist-glb.js') "// Generated by build-arcanist.ps1 from arcanist.glb. Do not edit.`nwindow.ARCANIST_GLB_B64 = '$b64';" -NoNewline -Encoding ascii
"wrote arcanist.glb, arcanist-glb.js and $Unity"
