# Rebuilds models/chimesinger.glb (WebP, browser) and the Unity copy (JPEG) from the Meshy sources with Blender, then
# wraps the browser GLB in chimesinger-glb.js so pages opened from disk (file://) can load it.
#   powershell -File build-chimesinger.ps1 -RunRef <Soldier.glb> [-Source <meshy body .glb>] [-Staff <meshy staff .glb>] [-Unity <out .glb>]
param(
  [string]$Source = (Get-ChildItem (Join-Path $PSScriptRoot 'upload\Meshy') -Filter '*Chimesinger_1*texture.glb' | Select-Object -First 1).FullName,
  [string]$Staff = (Get-ChildItem (Join-Path $PSScriptRoot 'upload\Meshy') -Filter '*Chimesinger_Staff*texture.glb' | Select-Object -First 1).FullName,
  [string]$Blender = 'C:\Program Files\Blender Foundation\Blender 5.2\blender.exe',
  # Mixamo-skeleton GLB whose 'Run' clip drives Run/Sprint (three.js examples/models/gltf/Soldier.glb). Not committed.
  [Parameter(Mandatory = $true)][string]$RunRef,
  [string]$Unity = (Join-Path $PSScriptRoot '..\..\..\unity\Assets\LastBell\Characters\Chimesinger\Resources\Characters\Chimesinger.glb')
)
$ErrorActionPreference = 'Stop'
$work = Join-Path $env:TEMP 'lastbell-chimesinger-build'; New-Item -ItemType Directory -Force $work | Out-Null
$glb = Join-Path $PSScriptRoot 'chimesinger.glb'
New-Item -ItemType Directory -Force (Split-Path $Unity) | Out-Null
& $Blender -b -P (Join-Path $PSScriptRoot 'blender\chimesinger_prep.py') -- $Source $work 50000 $Staff | Select-String '^(TRIS|STAFF_TRIS|GLOW)|Error|Traceback'
& $Blender -b (Join-Path $work 'chimesinger_prep.blend') -P (Join-Path $PSScriptRoot 'blender\chimesinger_rig.py') -- $work $glb $RunRef $Unity | Select-String '^(PROXY|STANCE|UNWEIGHTED|MOCAP|EXPORTED)|Error|Traceback'
$b64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($glb))
Set-Content (Join-Path $PSScriptRoot 'chimesinger-glb.js') "// Generated by build-chimesinger.ps1 from chimesinger.glb. Do not edit.`nwindow.CHIMESINGER_GLB_B64 = '$b64';" -NoNewline -Encoding ascii
"wrote chimesinger.glb, chimesinger-glb.js and $Unity"
