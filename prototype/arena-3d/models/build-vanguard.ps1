# Rebuilds models/vanguard.glb from the Meshy source with Blender, then wraps it in vanguard-glb.js so pages
# opened straight from disk (file://) can load it without a web server.
#   powershell -File build-vanguard.ps1 [-Source <meshy .glb>] [-Blender <blender.exe>]
param(
  [string]$Source = (Get-ChildItem (Join-Path $PSScriptRoot 'upload\Meshy') -Filter *texture.glb | Select-Object -First 1).FullName,
  [string]$Blender = 'C:\Program Files\Blender Foundation\Blender 5.2\blender.exe',
  # Mixamo-skeleton GLB whose 'Run' clip drives Run/Sprint (three.js examples/models/gltf/Soldier.glb). Not committed:
  # it's Mixamo content. Without it, rig.py falls back to the procedural gait.
  [string]$RunRef = ''
)
$ErrorActionPreference = 'Stop'
$work = Join-Path $env:TEMP 'lastbell-vanguard-build'; New-Item -ItemType Directory -Force $work | Out-Null
$glb = Join-Path $PSScriptRoot 'vanguard.glb'
& $Blender -b -P (Join-Path $PSScriptRoot 'blender\prep.py') -- $Source $work 40000 | Select-String '^(TRIS|GLOW)|Error|Traceback'
& $Blender -b (Join-Path $work 'vanguard_prep.blend') -P (Join-Path $PSScriptRoot 'blender\rig.py') -- $work $glb $RunRef | Select-String '^(PROXY|MOCAP|EXPORTED)|Error|Traceback'
$b64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($glb))
Set-Content (Join-Path $PSScriptRoot 'vanguard-glb.js') "// Generated by build-vanguard.ps1 from vanguard.glb. Do not edit.`nwindow.VANGUARD_GLB_B64 = '$b64';" -NoNewline -Encoding ascii
"wrote vanguard.glb and vanguard-glb.js"
